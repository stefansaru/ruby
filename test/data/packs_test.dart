import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:ruby/data/cases.dart';
import 'package:ruby/data/settings.dart';
import 'package:ruby/engine/case_text.dart';
import 'package:ruby/engine/clue.dart';
import 'package:ruby/engine/logic_solver.dart';
import 'package:ruby/engine/model.dart';
import 'package:ruby/engine/wording.dart';
import 'package:ruby/gen/gen_campaign.dart';
import 'package:ruby/gen/gen_case.dart';
import 'package:ruby/gen/gen_check.dart';
import 'package:ruby/gen/gen_config.dart';
import 'package:ruby/gen/gen_render.dart';

void main() {
  test('there is a pack for every tier and a slot for every case', () {
    expect(casePacks.keys, <String>[for (final t in Tier.values) t.name]);
    for (final tier in Tier.values) {
      expect(
        casePacks[tier.name],
        hasLength(campaign(tier).length),
        reason: tier.name,
      );
    }
  });

  for (final tier in Tier.values) {
    final pack = casePacks[tier.name]!;

    test('GEN-010 GEN-013 GEN-014 GEN-015 GEN-019 GEN-020 '
        'every ${tier.name} case passes the honest check', () {
      for (var i = 0; i < pack.length; i++) {
        expect(
          checkShipped(pack[i], tier),
          isNull,
          reason: '${tier.name} #${i + 1}',
        );
      }
    });

    test('GEN-009 every ${tier.name} case is stored exactly as written', () {
      final slots = campaign(tier);
      final titles = <String>{};
      for (var i = 0; i < pack.length; i++) {
        final c = parseCase(pack[i]);
        expect(c.id, slots[i].id);
        expect(c.setting, slots[i].setting);
        expect(c.liar, slots[i].liar);
        expect(c.noTouch, slots[i].noTouch);
        expect(c.people.length, slots[i].people);
        expect(writeCase(c), pack[i]);
        expect(titles.add(c.title), isTrue, reason: 'title used twice');
      }
    });

    test('GEN-024 every ${tier.name} clue reads as a full sentence', () {
      final compass = RegExp(r'\b(north|south|east|west)\b');
      for (final text in pack) {
        final c = parseCase(text);
        for (final clue in c.clues) {
          final s = describeClue(c, clue);
          expect(s, endsWith('.'));
          expect(s, isNot(contains('null')));
          expect(s, isNot(contains('  ')));
          expect(s.toLowerCase(), isNot(matches(compass)));
        }
        expect(describeVictim(c), contains('alone with the murderer'));
      }
    });

    test('GEN-021 no ${tier.name} statement mentions the victim', () {
      for (final text in pack) {
        final c = parseCase(text);
        for (final clue in c.clues) {
          if (clue is Rel) expect(clue.other, isNot(c.victim));
          if (clue is AloneWith) expect(clue.others, isNot(contains(c.victim)));
        }
      }
    });
  }

  test('GEN-015 each tier needs its own techniques and no harder ones', () {
    for (final tier in Tier.values) {
      for (final text in casePacks[tier.name]!) {
        final c = parseCase(text);
        final hardest = solveLogic(c).hardest;
        expect(tier.accepts(hardest), isTrue, reason: c.id);
        // Without its hardest technique the case is not solved.
        if (hardest.index > Technique.single.index) {
          final below = Technique.values[hardest.index - 1];
          expect(solveLogic(c, max: below).solved, isFalse, reason: c.id);
        }
      }
    }
  });

  test('GEN-026 a hint is available from any correct partial placement', () {
    for (final tier in Tier.values) {
      final c = parseCase(casePacks[tier.name]!.first);
      final answer = c.solution!;
      for (var placed = 0; placed < c.people.length; placed++) {
        final fixed = <int, int>{for (var p = 0; p < placed; p++) p: answer[p]};
        final r = solveLogic(c, fixed: fixed);
        expect(r.solved, isTrue, reason: '${c.id} with $placed placed');
        expect(r.pos, answer);
      }
    }
  });

  test('GEN-022 pack files carry the generated header', () {
    for (final tier in Tier.values) {
      final file = File('lib/data/${packFileName(tier)}');
      final text = file.readAsStringSync();
      expect(text, startsWith('// GENERATED by '));
      expect(text, contains('do not edit by hand'));
      expect(text, contains('const List<String> ${packVariable(tier)} ='));
    }
  });

  test('GEN-022 regenerating a pack reproduces the file byte for byte', () {
    // The two cheapest packs; `generate_cases.dart --dry-run` covers all.
    for (final tier in <Tier>[Tier.tutorial, Tier.easy]) {
      final cases = <CaseDef>[
        for (final cfg in campaign(tier)) generateCase(cfg).result!,
      ];
      final onDisk = File('lib/data/${packFileName(tier)}')
          .readAsStringSync()
          .replaceAll('\r\n', '\n');
      expect(renderPack(tier, cases), onDisk, reason: tier.name);
    }
  });

  test('every case uses a known setting and only its areas and objects', () {
    for (final tier in Tier.values) {
      for (final text in casePacks[tier.name]!) {
        final c = parseCase(text);
        final setting = settings.firstWhere(
          (SettingDef s) => s.id == c.setting,
        );
        final areaNames = <String>{for (final a in setting.areas) a.name};
        for (final a in c.areas) {
          expect(areaNames, contains(a.name), reason: c.id);
        }
        for (final k in c.kinds) {
          final spec = setting.kinds.firstWhere(
            (KindSpec s) => s.code == k.code,
          );
          expect(spec.name, k.name);
          expect(spec.sit, k.canOccupy);
        }
      }
    }
  });
}
